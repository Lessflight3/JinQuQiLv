const std::vector<Question> &questionsOf(QuizCategory category)
{
    static const std::vector<Question> common = buildCommonSense();
    static const std::vector<Question> tune = buildTune();
    static const std::vector<Question> aria = buildAria();
    static const std::vector<Question> picture = buildPicture();
    switch (category) {
    case QuizCategory::CommonSense:
        return common;
    case QuizCategory::Tune:
        return tune;
    case QuizCategory::Aria:
        return aria;
    case QuizCategory::Picture:
        return picture;
    }
    return common;
}

int questionCountOf(QuizCategory category)
{
    return static_cast<int>(questionsOf(category).size());
}

const std::vector<Question> &allQuestions()
{
    static const std::vector<Question> all = [] {
        std::vector<Question> result;
        for (int i = 0; i < kQuizCategoryCount; ++i) {
            const std::vector<Question> &part = questionsOf(static_cast<QuizCategory>(i));
            result.insert(result.end(), part.begin(), part.end());
        }
        return result;
    }();
    return all;
}
